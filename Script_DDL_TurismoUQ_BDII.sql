-- 1. MUNICIPIO
CREATE TABLE MUNICIPIO (
    id_municipio NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_municipio PRIMARY KEY (id_municipio),
    CONSTRAINT uk_municipio_nombre UNIQUE (nombre)
);
COMMENT ON TABLE MUNICIPIO IS 'Registra los 12 municipios del departamento del Quindío.';

-- 2. TIPO_ALOJAMIENTO
CREATE TABLE TIPO_ALOJAMIENTO (
    id_tipo_alojamiento NUMBER(4) GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_tipo_alojamiento PRIMARY KEY (id_tipo_alojamiento),
    CONSTRAINT uk_tipo_alojamiento_nombre UNIQUE (nombre)
);
COMMENT ON TABLE TIPO_ALOJAMIENTO IS 'Categorias de alojamientos (Finca cafetera, Hotel, Glamping, Hostal, etc.).';

-- 3. ALOJAMIENTO
CREATE TABLE ALOJAMIENTO (
    id_alojamiento NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
    id_municipio NUMBER(4) NOT NULL,
    id_tipo_alojamiento NUMBER(4) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    direccion VARCHAR2(150) NOT NULL,
    estrellas NUMBER(1) DEFAULT 3 NOT NULL,
    telefono VARCHAR2(20),
    email VARCHAR2(100),
    CONSTRAINT pk_alojamiento PRIMARY KEY (id_alojamiento),
    CONSTRAINT fk_alojamiento_municipio FOREIGN KEY (id_municipio) REFERENCES MUNICIPIO(id_municipio),
    CONSTRAINT fk_alojamiento_tipo FOREIGN KEY (id_tipo_alojamiento) REFERENCES TIPO_ALOJAMIENTO(id_tipo_alojamiento),
    CONSTRAINT chk_alojamiento_estrellas CHECK (estrellas BETWEEN 1 AND 5)
);
COMMENT ON TABLE ALOJAMIENTO IS 'Oferta de hospedaje en el departamento.';

-- 4. HABITACION
CREATE TABLE HABITACION (
    id_habitacion NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8) NOT NULL,
    numero_habitacion VARCHAR2(10) NOT NULL,
    capacidad NUMBER(2) NOT NULL,
    tipo VARCHAR2(30) NOT NULL,
    descripcion VARCHAR2(250),
    CONSTRAINT pk_habitacion PRIMARY KEY (id_habitacion),
    CONSTRAINT fk_habitacion_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO(id_alojamiento) ON DELETE CASCADE,
    CONSTRAINT uk_habitacion_num_aloj UNIQUE (id_alojamiento, numero_habitacion),
    CONSTRAINT chk_habitacion_capacidad CHECK (capacidad > 0),
    CONSTRAINT chk_habitacion_tipo CHECK (tipo IN ('SENCILLA', 'DOBLE', 'SUITE', 'CABAÑA', 'COMPARTIDA'))
);
COMMENT ON TABLE HABITACION IS 'Habitaciones u unidades alojables de cada establecimiento.';

-- 5. TEMPORADA
CREATE TABLE TEMPORADA (
    id_temporada NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(50) NOT NULL,
    tipo_temporada VARCHAR2(10) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    anio NUMBER(4) NOT NULL,
    CONSTRAINT pk_temporada PRIMARY KEY (id_temporada),
    CONSTRAINT chk_temporada_tipo CHECK (tipo_temporada IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT chk_temporada_fechas CHECK (fecha_fin >= fecha_inicio)
);
COMMENT ON TABLE TEMPORADA IS 'Rango de fechas que definen la estacionalidad del turismo por año.';

-- 6. TARIFA
CREATE TABLE TARIFA (
    id_tarifa NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_habitacion NUMBER(10) NOT NULL,
    id_temporada NUMBER(6) NOT NULL,
    precio_noche NUMBER(10, 2) NOT NULL,
    CONSTRAINT pk_tarifa PRIMARY KEY (id_tarifa),
    CONSTRAINT fk_tarifa_habitacion FOREIGN KEY (id_habitacion) REFERENCES HABITACION(id_habitacion) ON DELETE CASCADE,
    CONSTRAINT fk_tarifa_temporada FOREIGN KEY (id_temporada) REFERENCES TEMPORADA(id_temporada),
    CONSTRAINT uk_tarifa_hab_temp UNIQUE (id_habitacion, id_temporada),
    CONSTRAINT chk_tarifa_precio CHECK (precio_noche > 0)
);
COMMENT ON TABLE TARIFA IS 'Precio por noche de una habitacion segun la temporada vigente.';

-- 7. CLIENTE
CREATE TABLE CLIENTE (
    id_cliente NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(100) NOT NULL,
    documento_identidad VARCHAR2(20) NOT NULL,
    email VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(20),
    ciudad_origen VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uk_cliente_doc UNIQUE (documento_identidad),
    CONSTRAINT uk_cliente_email UNIQUE (email)
);
COMMENT ON TABLE CLIENTE IS 'Informacion de clientes registrados en la plataforma.';

-- 8. RESERVA
CREATE TABLE RESERVA (
    id_reserva NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_cliente NUMBER(10) NOT NULL,
    fecha_reserva DATE DEFAULT SYSDATE NOT NULL,
    fecha_checkin DATE NOT NULL,
    fecha_checkout DATE NOT NULL,
    estado VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
    CONSTRAINT chk_reserva_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA', 'COMPLETADA')),
    CONSTRAINT chk_reserva_fechas CHECK (fecha_checkout > fecha_checkin)
);
COMMENT ON TABLE RESERVA IS 'Encabezado de la reserva efectuada por un cliente.';

-- 9. RESERVA_HABITACION
CREATE TABLE RESERVA_HABITACION (
    id_reserva_habitacion NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva NUMBER(10) NOT NULL,
    id_habitacion NUMBER(10) NOT NULL,
    fecha_checkin DATE NOT NULL,
    fecha_checkout DATE NOT NULL,
    precio_noche_contratado NUMBER(10, 2) NOT NULL,
    CONSTRAINT pk_reserva_habitacion PRIMARY KEY (id_reserva_habitacion),
    CONSTRAINT fk_reshab_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA(id_reserva) ON DELETE CASCADE,
    CONSTRAINT fk_reshab_habitacion FOREIGN KEY (id_habitacion) REFERENCES HABITACION(id_habitacion),
    CONSTRAINT chk_reshab_fechas CHECK (fecha_checkout > fecha_checkin)
);
COMMENT ON TABLE RESERVA_HABITACION IS 'Detalle de habitaciones asociadas a una reserva.';

-- 10. PAGO
CREATE TABLE PAGO (
    id_pago NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva NUMBER(10) NOT NULL,
    fecha_pago DATE DEFAULT SYSDATE NOT NULL,
    monto NUMBER(10, 2) NOT NULL,
    metodo VARCHAR2(25) NOT NULL,
    estado VARCHAR2(15) DEFAULT 'EXITOSO' NOT NULL,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA(id_reserva) ON DELETE CASCADE,
    CONSTRAINT chk_pago_monto CHECK (monto > 0),
    CONSTRAINT chk_pago_metodo CHECK (metodo IN ('TARJETA_CREDITO', 'TARJETA_DEBITO', 'PSE', 'TRANSFERENCIA', 'EFECTIVO')),
    CONSTRAINT chk_pago_estado CHECK (estado IN ('EXITOSO', 'FALLIDO', 'PENDIENTE', 'REEMBOLSADO'))
);
COMMENT ON TABLE PAGO IS 'Transacciones de pago o abonos realizados a las reservas.';

-- 11. SERVICIO
CREATE TABLE SERVICIO (
    id_servicio NUMBER(8) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8) NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(250),
    precio NUMBER(10, 2) NOT NULL,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio),
    CONSTRAINT fk_servicio_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO(id_alojamiento) ON DELETE CASCADE,
    CONSTRAINT chk_servicio_precio CHECK (precio >= 0)
);
COMMENT ON TABLE SERVICIO IS 'Servicios complementarios ofrecidos por cada alojamiento.';

-- 12. RESERVA_SERVICIO
CREATE TABLE RESERVA_SERVICIO (
    id_reserva_servicio NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_reserva NUMBER(10) NOT NULL,
    id_servicio NUMBER(8) NOT NULL,
    cantidad NUMBER(4) DEFAULT 1 NOT NULL,
    precio_unitario NUMBER(10, 2) NOT NULL,
    CONSTRAINT pk_reserva_servicio PRIMARY KEY (id_reserva_servicio),
    CONSTRAINT fk_resserv_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA(id_reserva) ON DELETE CASCADE,
    CONSTRAINT fk_resserv_servicio FOREIGN KEY (id_servicio) REFERENCES SERVICIO(id_servicio),
    CONSTRAINT chk_resserv_cantidad CHECK (cantidad > 0)
);
COMMENT ON TABLE RESERVA_SERVICIO IS 'Servicios adicionales contratados en una reserva.';

-- 13. RESENA
CREATE TABLE RESENA (
    id_resena NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8) NOT NULL,
    id_cliente NUMBER(10) NOT NULL,
    id_reserva NUMBER(10) NOT NULL,
    calificacion NUMBER(1) NOT NULL,
    comentario VARCHAR2(500),
    fecha_resena DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_resena PRIMARY KEY (id_resena),
    CONSTRAINT fk_resena_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO(id_alojamiento),
    CONSTRAINT fk_resena_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
    CONSTRAINT fk_resena_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA(id_reserva),
    CONSTRAINT uk_resena_reserva UNIQUE (id_reserva),
    CONSTRAINT chk_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5)
);
COMMENT ON TABLE RESENA IS 'Evaluaciones dejadas por los clientes tras completar sus estadías.';

-- 14. USUARIO_SISTEMA
CREATE TABLE USUARIO_SISTEMA (
    id_usuario NUMBER(6) GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8), -- NULL si es administrador global
    username VARCHAR2(50) NOT NULL,
    password_hash VARCHAR2(100) NOT NULL,
    rol VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_usuario_sistema PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuario_alojamiento FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO(id_alojamiento),
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('ADMINISTRADOR', 'ENCARGADO'))
);
COMMENT ON TABLE USUARIO_SISTEMA IS 'Usuarios internos del sistema con roles especificos.';