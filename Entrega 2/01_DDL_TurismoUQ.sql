-- =============================================================================
-- 1. MUNICIPIO
-- Los 12 municipios del departamento del Quindío.
-- =============================================================================
CREATE TABLE MUNICIPIO (
    id_municipio    NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_municipio        PRIMARY KEY (id_municipio),
    CONSTRAINT uk_municipio_nombre UNIQUE (nombre)
);
COMMENT ON TABLE  MUNICIPIO         IS 'Los 12 municipios del departamento del Quindío.';
COMMENT ON COLUMN MUNICIPIO.nombre  IS 'Nombre oficial del municipio.';

-- =============================================================================
-- 2. TIPO_ALOJAMIENTO
-- Categorías que clasifican los establecimientos.
-- =============================================================================
CREATE TABLE TIPO_ALOJAMIENTO (
    id_tipo_alojamiento NUMBER(4)    GENERATED BY DEFAULT AS IDENTITY,
    nombre              VARCHAR2(50) NOT NULL,
    CONSTRAINT pk_tipo_alojamiento        PRIMARY KEY (id_tipo_alojamiento),
    CONSTRAINT uk_tipo_alojamiento_nombre UNIQUE (nombre)
);
COMMENT ON TABLE TIPO_ALOJAMIENTO IS 'Categorías de alojamiento (finca cafetera, hotel, glamping, hostal, etc.).';

-- =============================================================================
-- 3. ALOJAMIENTO
-- Establecimientos registrados en la plataforma.
-- =============================================================================
CREATE TABLE ALOJAMIENTO (
    id_alojamiento      NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    id_municipio        NUMBER(4)     NOT NULL,
    id_tipo_alojamiento NUMBER(4)     NOT NULL,
    nombre              VARCHAR2(100) NOT NULL,
    direccion           VARCHAR2(150) NOT NULL,
    estrellas           NUMBER(1)     DEFAULT 3 NOT NULL,
    telefono            VARCHAR2(20),
    email               VARCHAR2(100),
    CONSTRAINT pk_alojamiento         PRIMARY KEY (id_alojamiento),
    CONSTRAINT fk_aloj_municipio      FOREIGN KEY (id_municipio)        REFERENCES MUNICIPIO        (id_municipio),
    CONSTRAINT fk_aloj_tipo           FOREIGN KEY (id_tipo_alojamiento) REFERENCES TIPO_ALOJAMIENTO (id_tipo_alojamiento),
    CONSTRAINT chk_aloj_estrellas     CHECK (estrellas BETWEEN 1 AND 5)
);
COMMENT ON TABLE  ALOJAMIENTO           IS 'Establecimientos de hospedaje registrados en la plataforma.';
COMMENT ON COLUMN ALOJAMIENTO.estrellas IS 'Calificación auto-asignada por el alojamiento (1-5).';

-- Índice en FK municipio (consultas de ocupación por municipio son frecuentes)
CREATE INDEX idx_aloj_municipio ON ALOJAMIENTO (id_municipio);
CREATE INDEX idx_aloj_tipo      ON ALOJAMIENTO (id_tipo_alojamiento);

-- =============================================================================
-- 4. HABITACION
-- Unidades alojables de cada establecimiento.
-- =============================================================================
CREATE TABLE HABITACION (
    id_habitacion     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento    NUMBER(8)     NOT NULL,
    numero_habitacion VARCHAR2(10)  NOT NULL,
    capacidad         NUMBER(2)     NOT NULL,
    tipo              VARCHAR2(30)  NOT NULL,
    descripcion       VARCHAR2(250),
    CONSTRAINT pk_habitacion           PRIMARY KEY (id_habitacion),
    CONSTRAINT fk_hab_alojamiento      FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO (id_alojamiento) ON DELETE CASCADE,
    CONSTRAINT uk_hab_num_aloj         UNIQUE (id_alojamiento, numero_habitacion),
    CONSTRAINT chk_hab_capacidad       CHECK (capacidad > 0),
    -- GLAMPING añadido para alinearse con el tipo de alojamiento del mismo nombre
    CONSTRAINT chk_hab_tipo            CHECK (tipo IN ('SENCILLA','DOBLE','SUITE','CABAÑA','COMPARTIDA','GLAMPING'))
);
COMMENT ON TABLE  HABITACION                  IS 'Unidades alojables de cada establecimiento.';
COMMENT ON COLUMN HABITACION.numero_habitacion IS 'Número o código único dentro del alojamiento.';

-- Índice en FK (joins frecuentes hacia TARIFA y RESERVA_HABITACION)
CREATE INDEX idx_hab_alojamiento ON HABITACION (id_alojamiento);

-- =============================================================================
-- 5. TEMPORADA
-- Rangos de fechas que definen la estacionalidad (por año calendario).
-- =============================================================================
CREATE TABLE TEMPORADA (
    id_temporada   NUMBER(6)    GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(60) NOT NULL,
    tipo_temporada VARCHAR2(10) NOT NULL,
    fecha_inicio   DATE         NOT NULL,
    fecha_fin      DATE         NOT NULL,
    anio           NUMBER(4)    NOT NULL,
    CONSTRAINT pk_temporada       PRIMARY KEY (id_temporada),
    CONSTRAINT chk_temp_tipo      CHECK (tipo_temporada IN ('ALTA','MEDIA','BAJA')),
    CONSTRAINT chk_temp_fechas    CHECK (fecha_fin >= fecha_inicio)
);
COMMENT ON TABLE  TEMPORADA              IS 'Ventanas de estacionalidad turística definidas por año calendario.';
COMMENT ON COLUMN TEMPORADA.tipo_temporada IS 'ALTA = Semana Santa / mitad de año / puentes / dic-ene. MEDIA y BAJA en lo demás.';

-- =============================================================================
-- 6. TARIFA
-- Precio por noche de una habitación para una temporada específica.
-- Una tarifa no es un porcentaje fijo: cada alojamiento fija su propio precio.
-- =============================================================================
CREATE TABLE TARIFA (
    id_tarifa     NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_habitacion NUMBER(10)   NOT NULL,
    id_temporada  NUMBER(6)    NOT NULL,
    precio_noche  NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_tarifa           PRIMARY KEY (id_tarifa),
    CONSTRAINT fk_tarifa_hab       FOREIGN KEY (id_habitacion) REFERENCES HABITACION  (id_habitacion) ON DELETE CASCADE,
    CONSTRAINT fk_tarifa_temp      FOREIGN KEY (id_temporada)  REFERENCES TEMPORADA   (id_temporada),
    CONSTRAINT uk_tarifa_hab_temp  UNIQUE (id_habitacion, id_temporada),
    CONSTRAINT chk_tarifa_precio   CHECK (precio_noche > 0)
);
COMMENT ON TABLE TARIFA IS 'Precio por noche de una habitación para una temporada específica.';

-- Índice en FK (fn_valor_estadia hace JOIN habitacion+temporada miles de veces)
CREATE INDEX idx_tarifa_hab  ON TARIFA (id_habitacion);
CREATE INDEX idx_tarifa_temp ON TARIFA (id_temporada);

-- =============================================================================
-- 7. CLIENTE
-- Personas registradas en la plataforma.
-- =============================================================================
CREATE TABLE CLIENTE (
    id_cliente          NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    nombre              VARCHAR2(100) NOT NULL,
    documento_identidad VARCHAR2(20)  NOT NULL,
    email               VARCHAR2(100) NOT NULL,
    telefono            VARCHAR2(20),
    ciudad_origen       VARCHAR2(50)  NOT NULL,
    CONSTRAINT pk_cliente      PRIMARY KEY (id_cliente),
    CONSTRAINT uk_cliente_doc  UNIQUE (documento_identidad),
    CONSTRAINT uk_cliente_mail UNIQUE (email)
);
COMMENT ON TABLE CLIENTE IS 'Clientes registrados en TurismoUQ.';

-- =============================================================================
-- 8. RESERVA
-- Encabezado de reserva (puede incluir varias habitaciones en RESERVA_HABITACION).
-- =============================================================================
CREATE TABLE RESERVA (
    id_reserva    NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_cliente    NUMBER(10)   NOT NULL,
    fecha_reserva DATE         DEFAULT SYSDATE NOT NULL,
    fecha_checkin DATE         NOT NULL,
    fecha_checkout DATE        NOT NULL,
    estado        VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT pk_reserva          PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_cliente  FOREIGN KEY (id_cliente) REFERENCES CLIENTE (id_cliente),
    CONSTRAINT chk_reserva_estado  CHECK (estado IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
    CONSTRAINT chk_reserva_fechas  CHECK (fecha_checkout > fecha_checkin)
);
COMMENT ON TABLE  RESERVA        IS 'Encabezado de reserva: cliente, fechas marco y estado global.';
COMMENT ON COLUMN RESERVA.estado IS 'PENDIENTE→CONFIRMADA→COMPLETADA o CANCELADA.';

-- Índice en FK cliente + columna de estado (filtrada en múltiples consultas)
CREATE INDEX idx_reserva_cliente ON RESERVA (id_cliente);
CREATE INDEX idx_reserva_estado  ON RESERVA (estado);
CREATE INDEX idx_reserva_fechas  ON RESERVA (fecha_checkin, fecha_checkout);

-- =============================================================================
-- 9. RESERVA_HABITACION
-- Detalle por habitación dentro de una reserva.
-- Cada línea puede tener fechas propias (alguien del grupo llega un día después).
-- =============================================================================
CREATE TABLE RESERVA_HABITACION (
    id_reserva_habitacion  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_reserva             NUMBER(10)   NOT NULL,
    id_habitacion          NUMBER(10)   NOT NULL,
    fecha_checkin          DATE         NOT NULL,
    fecha_checkout         DATE         NOT NULL,
    num_huespedes          NUMBER(2)    DEFAULT 1 NOT NULL,
    precio_noche_contratado NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_reshab          PRIMARY KEY (id_reserva_habitacion),
    CONSTRAINT fk_reshab_reserva  FOREIGN KEY (id_reserva)    REFERENCES RESERVA    (id_reserva)    ON DELETE CASCADE,
    CONSTRAINT fk_reshab_hab      FOREIGN KEY (id_habitacion) REFERENCES HABITACION (id_habitacion),
    CONSTRAINT chk_reshab_fechas  CHECK (fecha_checkout > fecha_checkin),
    CONSTRAINT chk_reshab_huesp   CHECK (num_huespedes > 0)
);
COMMENT ON TABLE  RESERVA_HABITACION                       IS 'Líneas de habitación por reserva (fechas pueden diferir del encabezado).';
COMMENT ON COLUMN RESERVA_HABITACION.precio_noche_contratado IS 'Promedio ponderado noche calculado por fn_valor_estadia al crear la reserva.';

-- Índices críticos para el trigger anti-solapamiento y las consultas de ocupación
CREATE INDEX idx_reshab_reserva   ON RESERVA_HABITACION (id_reserva);
CREATE INDEX idx_reshab_hab       ON RESERVA_HABITACION (id_habitacion);
CREATE INDEX idx_reshab_fechas    ON RESERVA_HABITACION (id_habitacion, fecha_checkin, fecha_checkout);

-- =============================================================================
-- 10. PAGO
-- Abonos y pagos asociados a una reserva (puede haber varios por reserva).
-- =============================================================================
CREATE TABLE PAGO (
    id_pago    NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_reserva NUMBER(10)   NOT NULL,
    fecha_pago DATE         DEFAULT SYSDATE NOT NULL,
    monto      NUMBER(10,2) NOT NULL,
    metodo     VARCHAR2(25) NOT NULL,
    estado     VARCHAR2(15) DEFAULT 'EXITOSO' NOT NULL,
    CONSTRAINT pk_pago         PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_reserva FOREIGN KEY (id_reserva) REFERENCES RESERVA (id_reserva) ON DELETE CASCADE,
    CONSTRAINT chk_pago_monto  CHECK (monto > 0),
    CONSTRAINT chk_pago_metodo CHECK (metodo IN ('TARJETA_CREDITO','TARJETA_DEBITO','PSE','TRANSFERENCIA','EFECTIVO')),
    CONSTRAINT chk_pago_estado CHECK (estado IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO'))
);
COMMENT ON TABLE PAGO IS 'Abonos y pagos asociados a una reserva. Una reserva se considera saldada cuando SUM(monto) donde estado=EXITOSO >= valor total.';

CREATE INDEX idx_pago_reserva ON PAGO (id_reserva);
CREATE INDEX idx_pago_fecha   ON PAGO (fecha_pago);

-- =============================================================================
-- 11. SERVICIO
-- Servicios complementarios ofrecidos por cada alojamiento.
-- El mismo nombre en dos alojamientos distintos son servicios independientes.
-- =============================================================================
CREATE TABLE SERVICIO (
    id_servicio    NUMBER(8)     GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8)     NOT NULL,
    nombre         VARCHAR2(100) NOT NULL,
    descripcion    VARCHAR2(250),
    precio         NUMBER(10,2)  NOT NULL,
    CONSTRAINT pk_servicio        PRIMARY KEY (id_servicio),
    CONSTRAINT fk_serv_aloj       FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO (id_alojamiento) ON DELETE CASCADE,
    CONSTRAINT chk_serv_precio    CHECK (precio >= 0)
);
COMMENT ON TABLE SERVICIO IS 'Servicios complementarios (desayuno, tour, transporte…) por alojamiento.';

CREATE INDEX idx_serv_aloj ON SERVICIO (id_alojamiento);

-- =============================================================================
-- 12. RESERVA_SERVICIO
-- Servicios contratados dentro de una reserva.
-- UNIQUE (id_reserva, id_servicio): para agregar más unidades se usa cantidad.
-- =============================================================================
CREATE TABLE RESERVA_SERVICIO (
    id_reserva_servicio NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    id_reserva          NUMBER(10)   NOT NULL,
    id_servicio         NUMBER(8)    NOT NULL,
    cantidad            NUMBER(4)    DEFAULT 1 NOT NULL,
    precio_unitario     NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_resserv           PRIMARY KEY (id_reserva_servicio),
    CONSTRAINT fk_resserv_reserva   FOREIGN KEY (id_reserva)  REFERENCES RESERVA  (id_reserva)  ON DELETE CASCADE,
    CONSTRAINT fk_resserv_servicio  FOREIGN KEY (id_servicio) REFERENCES SERVICIO (id_servicio),
    CONSTRAINT uk_resserv_res_serv  UNIQUE (id_reserva, id_servicio),   -- FIX: evita duplicar mismo servicio en misma reserva
    CONSTRAINT chk_resserv_cantidad CHECK (cantidad > 0)
);
COMMENT ON TABLE  RESERVA_SERVICIO          IS 'Servicios adicionales contratados en una reserva.';
COMMENT ON COLUMN RESERVA_SERVICIO.cantidad IS 'Número de unidades del mismo servicio (ej. 2 tours para 2 personas).';

CREATE INDEX idx_resserv_reserva  ON RESERVA_SERVICIO (id_reserva);
CREATE INDEX idx_resserv_servicio ON RESERVA_SERVICIO (id_servicio);

-- =============================================================================
-- 13. RESENA
-- Reseña de un cliente sobre un alojamiento tras estadía completada.
-- Un cliente puede reseñar el mismo alojamiento solo una vez (aunque haya varias reservas).
-- La FK a id_reserva sirve para verificar que existe reserva COMPLETADA.
-- =============================================================================
CREATE TABLE RESENA (
    id_resena      NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    id_alojamiento NUMBER(8)     NOT NULL,
    id_cliente     NUMBER(10)    NOT NULL,
    id_reserva     NUMBER(10)    NOT NULL,
    calificacion   NUMBER(1)     NOT NULL,
    comentario     VARCHAR2(500),
    fecha_resena   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_resena             PRIMARY KEY (id_resena),
    CONSTRAINT fk_resena_aloj        FOREIGN KEY (id_alojamiento) REFERENCES ALOJAMIENTO (id_alojamiento),
    CONSTRAINT fk_resena_cliente     FOREIGN KEY (id_cliente)     REFERENCES CLIENTE     (id_cliente),
    CONSTRAINT fk_resena_reserva     FOREIGN KEY (id_reserva)     REFERENCES RESERVA     (id_reserva),
    -- FIX: un cliente reseña un alojamiento una sola vez (no una vez por reserva)
    CONSTRAINT uk_resena_cli_aloj    UNIQUE (id_cliente, id_alojamiento),
    CONSTRAINT chk_resena_calif      CHECK (calificacion BETWEEN 1 AND 5)
);
COMMENT ON TABLE  RESENA                IS 'Reseñas de clientes tras estadías completadas (máx. 1 por cliente/alojamiento).';
COMMENT ON COLUMN RESENA.id_reserva     IS 'Reserva completada que habilita la reseña (trazabilidad).';

CREATE INDEX idx_resena_aloj   ON RESENA (id_alojamiento);
CREATE INDEX idx_resena_cliente ON RESENA (id_cliente);

