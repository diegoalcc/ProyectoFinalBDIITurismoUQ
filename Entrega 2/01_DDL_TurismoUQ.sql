-- =============================================================================
-- 15. AUDITORIA_TARIFA
-- Registro de cambios sobre la tabla TARIFA (quién, cuándo, precio anterior/nuevo).
-- Diseñada para el disparador de auditoría (ver 04_Triggers.sql).
-- =============================================================================
CREATE TABLE AUDITORIA_TARIFA (
    id_auditoria    NUMBER(12)   GENERATED BY DEFAULT AS IDENTITY,
    usuario_bd      VARCHAR2(128) NOT NULL,
    fecha_evento    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    tipo_operacion  VARCHAR2(10) NOT NULL,               -- INSERT / UPDATE / DELETE
    id_tarifa       NUMBER(10),
    id_habitacion   NUMBER(10),
    id_temporada    NUMBER(6),
    precio_anterior NUMBER(10,2),
    precio_nuevo    NUMBER(10,2),
    CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria),
    CONSTRAINT chk_aud_operacion   CHECK (tipo_operacion IN ('INSERT','UPDATE','DELETE'))
);
COMMENT ON TABLE  AUDITORIA_TARIFA              IS 'Histórico de cambios en tarifas: quién, cuándo, valor anterior y nuevo.';
COMMENT ON COLUMN AUDITORIA_TARIFA.usuario_bd   IS 'Función USER al momento del DML.';
COMMENT ON COLUMN AUDITORIA_TARIFA.precio_anterior IS 'NULL en INSERT.';
COMMENT ON COLUMN AUDITORIA_TARIFA.precio_nuevo    IS 'NULL en DELETE.';

CREATE INDEX idx_aud_tarifa_fecha ON AUDITORIA_TARIFA (fecha_evento);

